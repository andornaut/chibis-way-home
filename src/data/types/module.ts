// Half-chunk modules, the zone frames that draw composed pairs, and the certified chunk lists.

import type { CertifiedArena } from "./arena.ts";
import type { TilePoint } from "./geometry.ts";
import type { ChunkPlan, ChunkSlot, Difficulty, Instance, NoCross, TerrainRect } from "./stage.ts";

export type ZoneKey = "apartment" | "blue" | "countryside" | "home" | "industrial" | "woodland";
export type ModuleSide = "left" | "right";

// The terrain top at a module edge. An outer edge (a chunk's entry or exit) stands on a seam row;
// a joint edge (between the two halves) may stand on any row, both halves equal.
interface ModuleEdge {
  readonly row: number;
}

// A required-route target in module tiles: a surface under `at`, or, with xRange, an inclusive
// interval of Chibi's body top-left column on it.
export interface ModuleRouteTarget {
  readonly at: TilePoint;
  readonly xRange?: { readonly max: number; readonly min: number };
}

// primary: the walk clears the chunk; recovery: also every ledge, lift and shuttle and the exit
// landing; encounter: recovery plus raised refuges and cover over the whole composed pair.
export type ModuleRouteProfile = "encounter" | "primary" | "recovery";

// Half a chunk: MODULE_RULES.cols wide and as tall as a zone, its contents in its own tiles from
// its top-left. A pair of a left and a right module composes one certified chunk per zone.
export interface ChunkModule {
  // Kebab-case and never containing "--", which separates the halves in a pair id.
  readonly id: string;
  readonly backdrops?: readonly Instance[];
  // The module alone, graded by gameplay/design.md's Chunks section.
  readonly difficulty: Difficulty;
  // The count of its antagonist-role objects: 0 or 1.
  readonly encounters: 0 | 1;
  readonly entry: ModuleEdge;
  readonly exit: ModuleEdge;
  readonly noCross?: readonly NoCross[];
  readonly objects: readonly Instance[];
  readonly outOfReach?: readonly TilePoint[];
  readonly route: {
    readonly profile: ModuleRouteProfile;
    readonly targets?: readonly ModuleRouteTarget[];
  };
  readonly scenery?: readonly Instance[];
  // Halves it may fill. The outer edge of each listed side obeys the full seam rule.
  readonly sides: readonly ModuleSide[];
  readonly slots?: readonly ChunkSlot[];
  readonly solids: readonly TerrainRect[];
  readonly weight?: number;
  // Per-zone additions a boss needs, appended after both halves' objects.
  readonly zoneObjects?: Readonly<Partial<Record<ZoneKey, readonly Instance[]>>>;
  // Zones whose bindings it is authored for; a pair is admitted to the zones both halves list.
  readonly zones: readonly ZoneKey[];
}

// The joint rule between the halves: footing flat columns on each side at the joint row and
// headroom clear rows above them. cols: a module's width, half a chunk; rows: every zone's height.
export interface ModuleRules {
  readonly cols: number;
  readonly joint: { readonly footing: number; readonly headroom: number };
  readonly rows: number;
}

// How a zone draws its composed pairs and which pool entries are route skeleton. themes: the
// zone's stage themes, every composed pair drawn in each. connectors: pool chunks outside the
// certified list. frame: the zone's own layers over the composed chunk (roofs, wall bands, depth).
export interface ZoneFrame {
  readonly connectors: readonly string[];
  readonly frame: (chunk: ChunkPlan) => ChunkPlan;
  readonly themes: readonly string[];
}

// One certified middle chunk for a zone: a whole authored chunk (single) or a composed pair.
// layout: its physics fingerprint, independent of theme and skin. trace: the FNV-1a 64 hash of
// every required walk's behaviour trace. route: the hash of its required-route targets and slot
// fills. work: executed walk ticks, a deterministic cost hint for scheduling.
export interface CertifiedEntry {
  readonly encounters: 0 | 1;
  readonly grade: Difficulty;
  readonly id: string;
  readonly kind: "pair" | "single";
  readonly layout: string;
  readonly modules?: readonly [left: string, right: string];
  readonly route: string;
  readonly slots: { readonly door: number; readonly event: number };
  readonly trace: string;
  readonly work: number;
}

// A zone's certified list, generated by src/tools/chunkPairs.ts. inputs.data hashes the data the
// proofs read; inputs.proofs hashes the behaviour trace fixtures, the game-kit version and the
// certification tool's version.
export interface CertifiedChunks {
  // The zone's arenas that pass the arena step, sorted by id.
  readonly arenas: readonly CertifiedArena[];
  readonly entries: readonly CertifiedEntry[];
  readonly inputs: { readonly data: string; readonly proofs: string };
  readonly version: 1;
  readonly zone: ZoneKey;
}
